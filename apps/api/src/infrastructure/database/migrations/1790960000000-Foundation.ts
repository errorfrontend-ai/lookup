    await run(`GRANT UPDATE (status) ON app.ads, app.campaigns, app.listener_installs TO lookup_admin_api`);

    // lookup_fingerprint_worker — the fingerprints schema is its alone; the API gets nothing there.
    await run(`GRANT USAGE ON SCHEMA fingerprints TO lookup_fingerprint_worker`);

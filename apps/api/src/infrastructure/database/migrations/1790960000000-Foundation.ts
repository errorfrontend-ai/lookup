/**
 * Foundation schema for the thin slice: stations, portal users, clients, ads, action cards,
 * campaigns and their time windows, the fingerprint store, listener installs, recognition events
 * and the audit trail.
 *
 * Naming — every name is written out in full so it reads as plain English:
 *  - tables are plural nouns; timestamps end in `_at`; amounts carry their unit (`_milliseconds`);
 *  - constraints are `<table>_<subject>_<kind>`, kind being primary_key, foreign_key, unique, check
 *    or exclusion; indexes are `<table>_<columns>_index`; triggers `<table>_<what they do>`;
 *  - policies say who sees what: `<table>_station_isolation`, `<table>_admin_full_access`.
 *
 * Security (master plan, ADR-002):
 *  - every station-owned row carries station_id; composite foreign keys (id, station_id) stop a row
 *    in one station from pointing at another station's rows (foreign key checks bypass row-level
 *    security otherwise);
 *  - row-level security filters by app.current_station_id(), set per transaction by the API;
 *  - the fingerprints schema has no station data and is invisible to the API role;
 *  - tables are owned by lookup_schema_owner, which nothing logs in as;
 *  - privileges are granted per table and, where it matters, per column: password hashes, refresh
 *    tokens, approval status, platform roles and the ad → audio asset link can't be read or
 *    written by the API role directly. Those go through narrow SECURITY DEFINER functions added
 *    with the features that need them (sign-in in step 2, ingest in step 3);
 *  - no function is executable by PUBLIC unless granted, so a future SECURITY DEFINER function
 *    can't be called by a role it wasn't meant for.
 *
 * Scaling:
 *  - recognition_events (one row per identify, the fastest-growing table) is partitioned by month
 *    of received_at. Queries for a period touch only that period's partitions, and old months are
 *    detached or dropped whole rather than deleted row by row. app.create_recognition_event_partitions()
 *    creates months ahead of time; a default partition catches anything outside them. Its
 *    idempotency keys live in a small unpartitioned table so uniqueness holds across months;
 *  - fingerprints.hashes_version_1 holds every landmark hash (millions of rows per thousand ads):
 *    no per-row id, one covering index for the one lookup it serves, and a version in the name so a
 *    re-index builds a new table alongside the live one and switches over;
 *  - ids of high-volume rows are UUIDv7 generated by the API (time-ordered, so inserts stay at the
 *    end of the index); low-volume tables use gen_random_uuid();
 *  - the station context is transaction-local (set_config(..., true)), so the API works behind a
 *    transaction-mode connection pooler.
 */
